"""Portable FBNeo naming adapter; game bytes remain owned by each builder."""
import hashlib
import io
import json
from pathlib import Path
import re
import zipfile

HERE = Path(__file__).resolve().parent
QSOUND_SHA256 = '524a25bcd153be24594d37c0dbd334fe4f384f77da73c2058dc60fc1f581cf18'


def registry():
    value = json.loads((HERE / 'fbneo_names.json').read_text())
    if value.get('schema') != 1 or not isinstance(value.get('sets'), dict):
        raise ValueError('Invalid FBNeo naming registry')
    return value['sets']


def safe(name):
    return isinstance(name, str) and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', name) is not None


def project(setname, members, definitions=None):
    """Rename a complete byte/hash map, excluding only declared dependencies."""
    definitions = registry() if definitions is None else definitions
    if setname not in definitions:
        raise ValueError('No established FBNeo naming declaration for ' + setname)
    spec = definitions[setname]; names = spec['renames']; ignored = spec.get('ignored', {})
    if (not re.fullmatch(r'[a-z0-9_]+', spec['setname']) or not isinstance(names, dict)
            or not names or any(not safe(n) for n in [*names, *names.values()])
            or len(set(names.values())) != len(names) or set(names) & set(ignored)):
        raise ValueError('Unsafe or ambiguous FBNeo naming declaration')
    if set(members) - set(names) - set(ignored) - {'dl-1425.bin'} or set(names) - set(members):
        raise ValueError('FBNeo complete member inventory differs for ' + setname)
    for name, digest in dict(ignored, **{'dl-1425.bin': QSOUND_SHA256}).items():
        if name in members:
            value = members[name]
            if (hashlib.sha256(value).hexdigest() if isinstance(value, bytes) else value) != digest:
                raise ValueError('Invalid excluded FBNeo dependency: ' + name)
    return {names[n]: members[n] for n in names}


def tree(setname, members, definitions=None):
    definitions = registry() if definitions is None else definitions
    result = project(setname, members, definitions)
    return {'fbneo/' + definitions[setname]['setname'] + '.zip': result}


def declaration(setname, source_to_hbmame, definitions=None):
    definitions = registry() if definitions is None else definitions
    if setname not in definitions: return None
    spec = definitions[setname]; names = spec['renames']
    inverse = {v:k for k,v in source_to_hbmame.items()}
    if len(inverse) != len(source_to_hbmame) or set(names) != set(inverse):
        raise ValueError('Canonical/HBMAME/FBNeo complete member mapping differs: ' + setname)
    return {'setname':spec['setname'], 'renames':{inverse[n]:target for n,target in names.items()}}


def add_outputs(files, definitions=None):
    """Explicit native-builder boundary; never reads an installed ROM folder."""
    definitions = registry() if definitions is None else definitions
    additions = {}
    for path, value in list(files.items()):
        match = re.fullmatch(r'hbmame/([a-z0-9_]+)\.zip', path)
        if not match: continue
        if isinstance(value, bytes):
            with zipfile.ZipFile(io.BytesIO(value)) as archive:
                names = [i.filename for i in archive.infolist() if not i.is_dir()]
                if len(names) != len(set(names)): raise ValueError('Duplicate native ROM member')
                value = {n:archive.read(n) for n in names}
        for name, members in tree(match[1], value, definitions).items():
            if name in files or name in additions: raise ValueError('Duplicate FBNeo export')
            additions[name] = members
    files.update(additions)
    return additions


def expectations(expected, definitions=None):
    """Use independent producer SHA256 maps, never recipient-generated bytes."""
    files = {n:r['members'] for n,r in expected.items() if n.startswith('hbmame/') and 'members' in r}
    additions = add_outputs(files, definitions)
    if set(additions) & set(expected): raise ValueError('FBNeo oracle already declared')
    return expected | {n:{'members':m} for n,m in additions.items()}
